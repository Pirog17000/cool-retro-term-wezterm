"""Generate wezterm's CRT profile tables from cool-retro-term's built-in profiles.

Reads the profiles embedded in app/qml/ApplicationSettings.qml and the bundled
font list in app/fontmanager.cpp, and writes

  * third_party/wezterm/config/src/crt_profiles.rs   (effect values, Rust)
  * wezterm-crt/wezterm_modules/crt_data.lua          (profiles + fonts, Lua)

so the wezterm fork ships the exact same looks (Default Amber, Monochrome
Green, Apple ][, ...).  The logic lives in the hand-written crt.lua.

    python tools/gen_crt_profiles.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "app" / "qml" / "ApplicationSettings.qml"
DST = ROOT / "third_party" / "wezterm" / "config" / "src" / "crt_profiles.rs"
LUA_DST = ROOT / "wezterm-crt" / "wezterm_modules" / "crt_data.lua"

FLOAT_KEYS = [
    ("ambientLight", "ambient_light"),
    ("bloom", "bloom"),
    ("brightness", "brightness"),
    ("burnIn", "burn_in"),
    ("chromaColor", "chroma_color"),
    ("contrast", "contrast"),
    ("flickering", "flickering"),
    ("glowingLine", "glowing_line"),
    ("horizontalSync", "horizontal_sync"),
    ("jitter", "jitter"),
    ("rgbShift", "rgb_shift"),
    ("saturationColor", "saturation_color"),
    ("screenCurvature", "screen_curvature"),
    ("screenRadius", "screen_radius"),
    ("staticNoise", "static_noise"),
    ("frameSize", "frame_size"),
    ("frameShininess", "frame_shininess"),
    ("margin", "margin"),
    ("windowOpacity", "window_opacity"),
    ("lineSpacing", "line_spacing"),
]
COLOR_KEYS = [
    ("fontColor", "font_color", "#ff8100"),
    ("backgroundColor", "background_color", "#000000"),
    ("frameColor", "frame_color", "#ffffff"),
]


def hex_rgb(s):
    s = s.lstrip("#")
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))


def load_profiles():
    text = SRC.read_text(encoding="utf-8")
    profiles = []
    for m in re.finditer(r'text: "([^"]+)"\s*obj_string: \'(\{.*?\})\'', text, re.S):
        profiles.append((m.group(1), json.loads(m.group(2))))
    if not profiles:
        raise SystemExit("no profiles found")
    return profiles


def write_rust(profiles):
    out = [
        "// @generated by tools/gen_crt_profiles.py from cool-retro-term's",
        "// app/qml/ApplicationSettings.qml -- do not edit by hand.",
        "",
        "use crate::crt::CrtProfile;",
        "",
        f"pub const CRT_PROFILES: [CrtProfile; {len(profiles)}] = [",
    ]
    for name, d in profiles:
        out.append("    CrtProfile {")
        out.append(f"        name: {json.dumps(name)},")
        out.append(f"        font: {json.dumps(d.get('fontName', ''))},")
        for js, rs in FLOAT_KEYS:
            v = float(d.get(js, 0.0))
            out.append(f"        {rs}: {v!r},")
        for js, rs, default in COLOR_KEYS:
            r, g, b = hex_rgb(d.get(js, default))
            out.append(f"        {rs}: ({r}, {g}, {b}),")
        out.append(f"        rasterization: {int(d.get('rasterization', 0))},")
        out.append(f"        blinking_cursor: {str(bool(d.get('blinkingCursor', False))).lower()},")
        out.append("    },")
    out.append("];")
    out.append("")
    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {len(profiles)} profiles to {DST}")


def bundled_fonts():
    """FontManager::populateBundledFonts() -> [(id, name, file, pixel_size, scaled, family)]"""
    from PIL import ImageFont

    src = (ROOT / "app" / "fontmanager.cpp").read_text(encoding="utf-8")
    fonts = []
    pat = (r'addBundledFont\(\s*"([^"]+)",\s*"([^"]+)",\s*":/fonts/([^"]+)",'
           r'\s*([^,]+),\s*([^,]+),\s*(true|false)')
    for m in re.finditer(pat, src):
        fid, disp, path, _scale, px, scaled = m.groups()
        family = ImageFont.truetype(str(ROOT / "app" / "qml" / "fonts" / path), 12).getname()[0]
        fonts.append((fid, disp, path, int(px), scaled == "true", family))
    return fonts


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(profiles):
    fonts = bundled_fonts()
    lines = [
        "-- @generated by tools/gen_crt_profiles.py -- do not edit by hand.",
        "-- cool-retro-term built-in profiles and bundled fonts (used by crt.lua).",
        "local M = {}",
        "",
        "-- Bundled fonts in cool-retro-term's order.",
        "M.font_ids = {",
    ]
    for f in fonts:
        lines.append(f"  {lua_str(f[0])},")
    lines += ["}", "", "M.fonts = {"]
    for fid, disp, path, px, scaled, family in fonts:
        lines.append(f"  {fid} = {{ name = {lua_str(disp + (' (scaled)' if scaled and fid.endswith('_SCALED') else ''))}, "
                     f"family = {lua_str(family)}, file = {lua_str(path)}, "
                     f"pixel_size = {px}, scaled = {str(scaled).lower()} }},")
    lines += ["}", "", "M.profile_names = {"]
    for name, _ in profiles:
        lines.append(f"  {lua_str(name)},")
    lines += ["}", "", "M.profiles = {"]
    for name, d in profiles:
        fields = [f"font = {lua_str(d.get('fontName', 'TERMINESS_SCALED'))}"]
        for js, rs in FLOAT_KEYS:
            fields.append(f"{rs} = {float(d.get(js, 0.0))!r}")
        for js, rs, default in COLOR_KEYS:
            fields.append(f"{rs} = {lua_str(d.get(js, default))}")
        fields.append(f"rasterization = {int(d.get('rasterization', 0))}")
        fields.append(f"blinking_cursor = {str(bool(d.get('blinkingCursor', False))).lower()}")
        lines.append(f"  [{lua_str(name)}] = {{")
        for fld in fields:
            lines.append(f"    {fld},")
        lines.append("  },")
    lines += ["}", "", "return M", ""]
    LUA_DST.parent.mkdir(parents=True, exist_ok=True)
    LUA_DST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {LUA_DST}")


def main():
    profiles = load_profiles()
    write_rust(profiles)
    write_lua(profiles)


if __name__ == "__main__":
    main()
