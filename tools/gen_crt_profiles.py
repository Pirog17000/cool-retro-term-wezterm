"""Generate wezterm's CRT profile table from cool-retro-term's built-in profiles.

Reads the profiles embedded in app/qml/ApplicationSettings.qml and writes
third_party/wezterm/config/src/crt_profiles.rs so the wezterm fork ships the
exact same looks (Default Amber, Monochrome Green, Apple ][, ...).

    python tools/gen_crt_profiles.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "app" / "qml" / "ApplicationSettings.qml"
DST = ROOT / "third_party" / "wezterm" / "config" / "src" / "crt_profiles.rs"

FLOAT_KEYS = [
    ("ambientLight", "ambient_light"),
    ("bloom", "bloom"),
    ("brightness", "brightness"),
    ("burnIn", "burn_in"),
    ("chromaColor", "chroma_color"),
    ("contrast", "contrast"),
    ("flickering", "flickering"),
    ("glowingLine", "glowing_line"),
    ("horizontalSync", "horizontal_sync"),
    ("jitter", "jitter"),
    ("rgbShift", "rgb_shift"),
    ("saturationColor", "saturation_color"),
    ("screenCurvature", "screen_curvature"),
    ("screenRadius", "screen_radius"),
    ("staticNoise", "static_noise"),
    ("frameSize", "frame_size"),
    ("frameShininess", "frame_shininess"),
    ("margin", "margin"),
    ("windowOpacity", "window_opacity"),
    ("lineSpacing", "line_spacing"),
]
COLOR_KEYS = [
    ("fontColor", "font_color", "#ff8100"),
    ("backgroundColor", "background_color", "#000000"),
    ("frameColor", "frame_color", "#ffffff"),
]


def hex_rgb(s):
    s = s.lstrip("#")
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))


def main():
    text = SRC.read_text(encoding="utf-8")
    profiles = []
    for m in re.finditer(r'text: "([^"]+)"\s*obj_string: \'(\{.*?\})\'', text, re.S):
        profiles.append((m.group(1), json.loads(m.group(2))))
    if not profiles:
        raise SystemExit("no profiles found")

    out = [
        "// @generated by tools/gen_crt_profiles.py from cool-retro-term's",
        "// app/qml/ApplicationSettings.qml -- do not edit by hand.",
        "",
        "use crate::crt::CrtProfile;",
        "",
        f"pub const CRT_PROFILES: [CrtProfile; {len(profiles)}] = [",
    ]
    for name, d in profiles:
        out.append("    CrtProfile {")
        out.append(f"        name: {json.dumps(name)},")
        out.append(f"        font: {json.dumps(d.get('fontName', ''))},")
        for js, rs in FLOAT_KEYS:
            v = float(d.get(js, 0.0))
            out.append(f"        {rs}: {v!r},")
        for js, rs, default in COLOR_KEYS:
            r, g, b = hex_rgb(d.get(js, default))
            out.append(f"        {rs}: ({r}, {g}, {b}),")
        out.append(f"        rasterization: {int(d.get('rasterization', 0))},")
        out.append(f"        blinking_cursor: {str(bool(d.get('blinkingCursor', False))).lower()},")
        out.append("    },")
    out.append("];")
    out.append("")
    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {len(profiles)} profiles to {DST}")

    write_lua(profiles)


def bundled_fonts():
    """FontManager::populateBundledFonts() -> {id: (file, pixel_size, scaled, family)}"""
    from PIL import ImageFont

    src = (ROOT / "app" / "fontmanager.cpp").read_text(encoding="utf-8")
    fonts = {}
    pat = (r'addBundledFont\(\s*"([^"]+)",\s*"([^"]+)",\s*":/fonts/([^"]+)",'
           r'\s*([^,]+),\s*([^,]+),\s*(true|false)')
    for m in re.finditer(pat, src):
        fid, _disp, path, _scale, px, scaled = m.groups()
        family = ImageFont.truetype(str(ROOT / "app" / "qml" / "fonts" / path), 12).getname()[0]
        fonts[fid] = (path, int(px), scaled == "true", family)
    return fonts


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(profiles):
    fonts = bundled_fonts()
    lines = [
        "-- @generated by tools/gen_crt_profiles.py -- do not edit by hand.",
        "-- cool-retro-term profiles and bundled fonts for the wezterm CRT build.",
        "--",
        "--   local crt = require 'crt'",
        "--   crt.apply(config, { profile = 'Monochrome Green' })",
        "--",
        "-- The CRT effect values themselves live in the wezterm binary",
        "-- (config.crt); this module only applies the matching font, line",
        "-- height, padding and cursor style that cool-retro-term uses.",
        "local wezterm = require 'wezterm'",
        "local M = {}",
        "",
        "M.fonts = {",
    ]
    for fid, (path, px, scaled, family) in sorted(fonts.items()):
        lines.append(f"  {fid} = {{ family = {lua_str(family)}, file = {lua_str(path)}, "
                     f"pixel_size = {px}, scaled = {str(scaled).lower()} }},")
    lines += ["}", "", "M.profiles = {"]
    for name, d in profiles:
        lines.append(f"  [{lua_str(name)}] = {{ font = {lua_str(d.get('fontName', 'TERMINESS_SCALED'))}, "
                     f"line_spacing = {float(d.get('lineSpacing', 0.1))!r}, margin = {float(d.get('margin', 0.5))!r}, "
                     f"screen_radius = {float(d.get('screenRadius', 0.2))!r}, "
                     f"blinking_cursor = {str(bool(d.get('blinkingCursor', False))).lower()} }},")
    lines += ["}", "", "M.profile_names = {"]
    for name, _ in profiles:
        lines.append(f"  {lua_str(name)},")
    lines += ["}", ""]
    lines += LUA_TAIL.splitlines()
    out = ROOT / "wezterm-crt" / "wezterm_modules" / "crt.lua"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


LUA_TAIL = r'''
local function lint(a, b, t) return (1 - t) * a + t * b end

--- Apply a cool-retro-term profile to a wezterm config.
--- opts.profile    : profile name (default: config.crt.profile or "Default Amber")
--- opts.font       : font id from M.fonts to override the profile font
--- opts.cell_height: target cell height in pixels for pixel fonts (default 24)
--- opts.font_size  : font size in points for vector fonts (default 13)
--- Any other key in opts is copied into config.crt (effect overrides).
function M.apply(config, opts)
  opts = opts or {}
  config.crt = config.crt or {}
  local name = opts.profile or config.crt.profile or 'Default Amber'
  local p = M.profiles[name]
  if not p then
    wezterm.log_warn('crt: unknown profile ' .. tostring(name) .. ', using Default Amber')
    name = 'Default Amber'
    p = M.profiles[name]
  end
  config.crt.profile = name
  for k, v in pairs(opts) do
    if k ~= 'profile' and k ~= 'font' and k ~= 'cell_height' and k ~= 'font_size' then
      config.crt[k] = v
    end
  end

  local f = M.fonts[opts.font or p.font] or M.fonts.TERMINESS_SCALED
  config.font_dirs = config.font_dirs or {}
  table.insert(config.font_dirs, wezterm.executable_dir .. '/fonts')
  config.font = wezterm.font_with_fallback { f.family, 'Consolas' }

  if f.scaled then
    -- Pixel fonts look right at integer multiples of their design size.
    local target = opts.cell_height or 24
    local scale = math.max(1, math.floor(target / f.pixel_size + 0.5))
    config.font_size = f.pixel_size * scale * 0.75
    config.freetype_load_target = 'Mono'
    config.freetype_render_target = 'Mono'
  else
    config.font_size = opts.font_size or 13
  end

  config.line_height = 1.0 + (p.line_spacing or 0)
  local radius = lint(4.0, 120.0, p.screen_radius or 0.2)
  local pad = math.floor(lint(1.0, 40.0, p.margin or 0.5) + (1.0 - math.sqrt(0.5)) * radius)
  config.window_padding = { left = pad, right = pad, top = pad, bottom = pad }
  config.default_cursor_style = p.blinking_cursor and 'BlinkingBlock' or 'SteadyBlock'
  return config
end

return M
'''


if __name__ == "__main__":
    main()
